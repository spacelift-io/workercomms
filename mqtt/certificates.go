var invalidCertErr error = errors.New("invalid certificate")

// getMQTTCertPool returns a CertPool with some extra CA certs required for worker MQTT communication.
func getMQTTCertPool(additionalCerts []string) (*x509.CertPool, error) {
	pool, _ := x509.SystemCertPool()
	if pool == nil {
		pool = x509.NewCertPool()
	}

	for _, ca := range requiredCertificateAuthorities {
		ok := pool.AppendCertsFromPEM(ca)
		if !ok {
			return nil, invalidCertErr
		}
	}

	for _, ca := range additionalCerts {
		ok := pool.AppendCertsFromPEM([]byte(ca))
		if !ok {
			return nil, invalidCertErr
		}
	}

	return pool, nil
}
